//! Helpers for the Gemini Interactions LLM wrapper.

use talin_provider::gemini_interactions::types::{
    Function, Interaction, InteractionStatus, Step, Tool,
};

use crate::llm::LlmError;
use crate::llm::gemini_interactions::InteractionsBuiltinTool;
use crate::tools::ToolSpec;
use crate::utils::NoneIfEmpty;

/// Builds the Interactions API tool list from function specs and built-in tools.
pub(super) fn map_tools(
    tools: Vec<ToolSpec>,
    builtin_tools: Vec<InteractionsBuiltinTool>,
) -> Option<Vec<Tool>> {
    let function_tools = ToolSpec::into_functions(tools)
        .into_iter()
        .map(|function| Tool::Function(Function::from(function)));
    let builtin_tools = builtin_tools.into_iter().map(Tool::from);

    let tools = function_tools.chain(builtin_tools).collect::<Vec<_>>();
    tools.none_if_empty()
}

/// Extracts the steps generated by the model in the current turn.
///
/// The interaction carries the whole step history; the model's output is the trailing run of steps
/// after the last caller-provided input (user input or tool result).
pub(super) fn model_steps(interaction: &Interaction) -> Vec<Step> {
    let steps = interaction.steps.as_slice();

    let boundary = steps.iter().rposition(is_input_step);
    match boundary {
        Some(index) => steps[index + 1..].to_vec(),
        None => steps.to_vec(),
    }
}

/// Whether a step was provided by the caller rather than generated by the model.
fn is_input_step(step: &Step) -> bool {
    matches!(step, Step::UserInput(_) | Step::FunctionResult(_))
}

/// Maps a terminal interaction status to an error, treating in-progress and successful statuses as
/// `Ok`.
pub(super) fn check_status(status: InteractionStatus) -> Result<(), LlmError> {
    match status {
        InteractionStatus::InProgress
        | InteractionStatus::RequiresAction
        | InteractionStatus::Completed
        | InteractionStatus::Incomplete => Ok(()),
        InteractionStatus::Failed => Err(LlmError::other("Gemini interaction failed")),
        InteractionStatus::Cancelled => Err(LlmError::other("Gemini interaction was cancelled")),
        // Handle future variants as success, since we don't know what they mean yet.
        _ => Ok(()),
    }
}
