/// Data of the part.
#[derive(Serialize, Deserialize, Debug, Clone)]
#[serde(rename_all = "camelCase")]
#[non_exhaustive]
pub enum Data {
    /// Inline text.
    Text(String),
    /// Inline media bytes.
    InlineData(Blob),
    /// A predicted [`FunctionCall`] returned from the model that contains a string representing the
    /// `FunctionDeclaration.name` with the arguments and their values.
    FunctionCall(FunctionCall),
    /// The result output of a [`FunctionCall`] that contains a string representing the
    /// `FunctionDeclaration.name` and a structured JSON object containing any output from the
    /// function is used as context to the model.
    FunctionResponse(FunctionResponse),
    /// URI based data.
    FileData(FileData),
    /// Code generated by the model that is meant to be executed.
    ExecutableCode(ExecutableCode),
    /// Result of executing the `ExecutableCode`.
    CodeExecutionResult(CodeExecutionResult),
    /// Server-side tool call. This field is populated when the model predicts a tool invocation
    /// that should be executed on the server. The client is expected to echo this message back to
    /// the API.
    ToolCall(ToolCall),
    /// Result of executing the server-side tool. This field is populated with the output of the
    /// server-side tool execution. The client is expected to echo this message back to the API.
    ToolResponse(ToolResponse),
}

/// Controls extra preprocessing of data.
#[derive(Serialize, Deserialize, Debug, Clone)]
#[serde(rename_all = "camelCase", untagged)]
#[non_exhaustive]
pub enum Metadata {
    /// Optional. Video metadata. The metadata should only be specified while the video data is
    /// presented in `inlineData` or `fileData`.
    VideoMetadata(VideoMetadata),
}

/// A content part that can be text, inline data, file data, or other types.
#[skip_serializing_none]
#[serde_as]
#[derive(Serialize, Deserialize, Debug, Clone)]
#[serde(rename_all = "camelCase")]
#[non_exhaustive]
pub struct Part {
    /// Thought from thinking models.
    pub thought: Option<bool>,

    /// An opaque signature for the thought so it can be reused in subsequent requests.
    /// A base64-encoded string.
    #[serde_as(as = "Option<Base64>")]
    pub thought_signature: Option<Vec<u8>>,

    /// Custom metadata associated with the Part. Agents using genai.Part as content representation
    /// may need to keep track of the additional information. For example it can be name of a
    /// file/source from which the Part originates or a way to multiplex multiple Part streams.
    pub part_metadata: Option<serde_json::Value>,

    /// Optional. Media resolution for the input media.
    pub media_resolution: Option<MediaResolution>,

    /// Data of the part.
    #[serde(flatten)]
    pub data: Data,

    /// Controls extra preprocessing of data.
    #[serde(flatten)]
    pub metadata: Option<Metadata>,
}
