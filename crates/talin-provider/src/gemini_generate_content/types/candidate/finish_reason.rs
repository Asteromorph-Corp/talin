use serde::{Deserialize, Serialize};

/// The reason why the model stopped generating tokens.
#[derive(Serialize, Deserialize, Debug, Clone, Copy, PartialEq, Eq)]
#[serde(rename_all = "SCREAMING_SNAKE_CASE")]
#[non_exhaustive]
pub enum FinishReason {
    /// Default value. This value is unused.
    FinishReasonUnspecified,
    /// Natural stop point of the model or provided stop sequence.
    Stop,
    /// The maximum number of tokens as specified in the request was reached.
    MaxTokens,
    /// The response candidate content was flagged for safety reasons.
    Safety,
    /// The response candidate content was flagged for recitation reasons.
    Recitation,
    /// The response candidate content was flagged for using an unsupported language.
    Language,
    /// Unknown reason.
    Other,
    /// Token generation stopped because the content contains forbidden terms.
    Blocklist,
    /// Token generation stopped for potentially containing prohibited content.
    ProhibitedContent,
    /// Token generation stopped because the content potentially contains SPII.
    Spii,
    /// The function call generated by the model is invalid.
    MalformedFunctionCall,
    /// Token generation stopped because generated images contain safety violations.
    ImageSafety,
    /// Image generation stopped because generated images has other prohibited content.
    ImageProhibitedContent,
    /// Image generation stopped because of other miscellaneous issue.
    ImageOther,
    /// The model was expected to generate an image, but none was generated.
    NoImage,
    /// Image generation stopped due to recitation.
    ImageRecitation,
    /// Model generated a tool call but no tools were enabled in the request.
    UnexpectedToolCall,
    /// Model called too many tools consecutively.
    TooManyToolCalls,
    /// Request has at least one thought signature missing.
    MissingThoughtSignature,
    /// Finished due to a malformed response.
    MalformedResponse,
    /// Request was filtered by an escalation rule.
    Escalation,
    /// Unknown reason not represented by this enum.
    #[serde(other)]
    Unknown,
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_finish_reason_wire() {
        assert_eq!(
            serde_json::to_string(&FinishReason::MalformedResponse).unwrap(),
            "\"MALFORMED_RESPONSE\""
        );
        assert_eq!(
            serde_json::from_str::<FinishReason>("\"MAX_TOKENS\"").unwrap(),
            FinishReason::MaxTokens
        );
        // Forward-compat: unknown server values do not fail deserialization.
        assert_eq!(
            serde_json::from_str::<FinishReason>("\"BRAND_NEW_REASON\"").unwrap(),
            FinishReason::Unknown
        );
    }
}
