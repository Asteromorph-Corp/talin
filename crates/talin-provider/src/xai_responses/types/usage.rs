use serde::{Deserialize, Serialize};
use serde_with::skip_serializing_none;

/// Token usage information.
#[skip_serializing_none]
#[cfg_attr(test, derive(utoipa::ToSchema))]
#[derive(Serialize, Deserialize, Debug, Clone, Default)]
#[non_exhaustive]
pub struct ModelUsage {
    /// Token counts for the latest context window seen by the model.
    pub context_details: Option<ContextDetails>,

    /// Cost in nano US dollars for this request.
    pub cost_in_nano_usd: Option<i64>,

    /// Accurate cost of this request in USD ticks.
    pub cost_in_usd_ticks: Option<i64>,

    /// Number of input tokens used.
    pub input_tokens: u32,

    /// Breakdown of the input tokens.
    pub input_tokens_details: InputTokensDetails,

    /// Number of server side tools used.
    pub num_server_side_tools_used: u32,

    /// Number of sources used (for live search).
    pub num_sources_used: u32,

    /// Number of output tokens used.
    pub output_tokens: u32,

    /// Breakdown of the output tokens.
    pub output_tokens_details: OutputTokensDetails,

    /// Details about the server side tool usage.
    pub server_side_tool_usage_details: Option<ServerSideToolUsageDetails>,

    /// Total tokens used.
    pub total_tokens: u32,
}

/// Breakdown of the input tokens.
#[cfg_attr(test, derive(utoipa::ToSchema))]
#[derive(Serialize, Deserialize, Debug, Clone, Default)]
#[non_exhaustive]
pub struct InputTokensDetails {
    /// Token cached by xAI from previous requests and reused for this request.
    pub cached_tokens: u32,
}

/// Breakdown of the output tokens.
#[cfg_attr(test, derive(utoipa::ToSchema))]
#[derive(Serialize, Deserialize, Debug, Clone, Default)]
#[non_exhaustive]
pub struct OutputTokensDetails {
    /// Tokens generated by the model for reasoning.
    pub reasoning_tokens: u32,
}

/// Details about the server side tool usage.
#[cfg_attr(test, derive(utoipa::ToSchema))]
#[derive(Serialize, Deserialize, Debug, Clone, Default)]
#[serde(default)]
#[non_exhaustive]
pub struct ServerSideToolUsageDetails {
    /// Number of code interpreter calls.
    #[cfg_attr(test, schema(required = true))]
    pub code_interpreter_calls: u32,

    /// Number of document search calls.
    #[cfg_attr(test, schema(required = true))]
    pub document_search_calls: u32,

    /// Number of image generation calls.
    #[cfg_attr(test, schema(required = true))]
    pub image_generation_calls: u32,

    /// Number of file search calls.
    #[cfg_attr(test, schema(required = true))]
    pub file_search_calls: u32,

    /// Number of MCP calls.
    #[cfg_attr(test, schema(required = true))]
    pub mcp_calls: u32,

    /// Number of web search calls.
    #[cfg_attr(test, schema(required = true))]
    pub web_search_calls: u32,

    /// Number of X search calls.
    #[cfg_attr(test, schema(required = true))]
    pub x_search_calls: u32,

    /// Number of X posts fetched across all X search calls, including nested parent/quote posts
    /// and every post of a fetched thread, without de-duplication.
    #[cfg_attr(test, schema(required = true))]
    pub x_posts_fetched: u32,

    /// Number of X user profiles fetched across all X search calls, without de-duplication.
    #[cfg_attr(test, schema(required = true))]
    pub x_users_fetched: u32,
}

/// Token counts for the latest context window seen by the model.
///
/// In the non-agentic path these mirror [`input_tokens`](ModelUsage::input_tokens) and
/// [`output_tokens`](ModelUsage::output_tokens). In the agentic path they are reset on every
/// step and reflect the most recent step's prompt and output sizes. Informational only; not
/// used for billing.
#[cfg_attr(test, derive(utoipa::ToSchema))]
#[derive(Serialize, Deserialize, Debug, Clone, Default)]
#[non_exhaustive]
pub struct ContextDetails {
    /// Prompt tokens in the latest context.
    pub input_tokens: u32,

    /// Completion and reasoning tokens in the latest context.
    pub output_tokens: u32,
}

impl ModelUsage {
    /// Creates an empty [`ModelUsage`].
    pub fn new() -> Self {
        Self::default()
    }

    /// Sets the token counts for the latest context window seen by the model.
    pub fn with_context_details(mut self, context_details: ContextDetails) -> Self {
        self.context_details = Some(context_details);
        self
    }

    /// Sets the cost in nano US dollars for this request.
    pub fn with_cost_in_nano_usd(mut self, cost_in_nano_usd: i64) -> Self {
        self.cost_in_nano_usd = Some(cost_in_nano_usd);
        self
    }

    /// Sets the accurate cost of this request in USD ticks.
    pub fn with_cost_in_usd_ticks(mut self, cost_in_usd_ticks: i64) -> Self {
        self.cost_in_usd_ticks = Some(cost_in_usd_ticks);
        self
    }

    /// Sets the number of input tokens used.
    pub fn with_input_tokens(mut self, input_tokens: u32) -> Self {
        self.input_tokens = input_tokens;
        self
    }

    /// Sets the breakdown of the input tokens.
    pub fn with_input_tokens_details(mut self, input_tokens_details: InputTokensDetails) -> Self {
        self.input_tokens_details = input_tokens_details;
        self
    }

    /// Sets the number of server side tools used.
    pub fn with_num_server_side_tools_used(mut self, num_server_side_tools_used: u32) -> Self {
        self.num_server_side_tools_used = num_server_side_tools_used;
        self
    }

    /// Sets the number of sources used.
    pub fn with_num_sources_used(mut self, num_sources_used: u32) -> Self {
        self.num_sources_used = num_sources_used;
        self
    }

    /// Sets the number of output tokens used.
    pub fn with_output_tokens(mut self, output_tokens: u32) -> Self {
        self.output_tokens = output_tokens;
        self
    }

    /// Sets the breakdown of the output tokens.
    pub fn with_output_tokens_details(
        mut self,
        output_tokens_details: OutputTokensDetails,
    ) -> Self {
        self.output_tokens_details = output_tokens_details;
        self
    }

    /// Sets the details about the server side tool usage.
    pub fn with_server_side_tool_usage_details(
        mut self,
        server_side_tool_usage_details: ServerSideToolUsageDetails,
    ) -> Self {
        self.server_side_tool_usage_details = Some(server_side_tool_usage_details);
        self
    }

    /// Sets the total tokens used.
    pub fn with_total_tokens(mut self, total_tokens: u32) -> Self {
        self.total_tokens = total_tokens;
        self
    }
}

impl InputTokensDetails {
    /// Creates an [`InputTokensDetails`] with the given number of cached tokens.
    pub fn new(cached_tokens: u32) -> Self {
        Self { cached_tokens }
    }
}

impl OutputTokensDetails {
    /// Creates an [`OutputTokensDetails`] with the given number of reasoning tokens.
    pub fn new(reasoning_tokens: u32) -> Self {
        Self { reasoning_tokens }
    }
}

impl ServerSideToolUsageDetails {
    /// Creates an empty [`ServerSideToolUsageDetails`].
    pub fn new() -> Self {
        Self::default()
    }

    /// Sets the number of code interpreter calls.
    pub fn with_code_interpreter_calls(mut self, code_interpreter_calls: u32) -> Self {
        self.code_interpreter_calls = code_interpreter_calls;
        self
    }

    /// Sets the number of document search calls.
    pub fn with_document_search_calls(mut self, document_search_calls: u32) -> Self {
        self.document_search_calls = document_search_calls;
        self
    }

    /// Sets the number of image generation calls.
    pub fn with_image_generation_calls(mut self, image_generation_calls: u32) -> Self {
        self.image_generation_calls = image_generation_calls;
        self
    }

    /// Sets the number of file search calls.
    pub fn with_file_search_calls(mut self, file_search_calls: u32) -> Self {
        self.file_search_calls = file_search_calls;
        self
    }

    /// Sets the number of MCP calls.
    pub fn with_mcp_calls(mut self, mcp_calls: u32) -> Self {
        self.mcp_calls = mcp_calls;
        self
    }

    /// Sets the number of web search calls.
    pub fn with_web_search_calls(mut self, web_search_calls: u32) -> Self {
        self.web_search_calls = web_search_calls;
        self
    }

    /// Sets the number of X search calls.
    pub fn with_x_search_calls(mut self, x_search_calls: u32) -> Self {
        self.x_search_calls = x_search_calls;
        self
    }
}

impl ContextDetails {
    /// Creates a [`ContextDetails`] with the given prompt and output token counts.
    pub fn new(input_tokens: u32, output_tokens: u32) -> Self {
        Self {
            input_tokens,
            output_tokens,
        }
    }
}
