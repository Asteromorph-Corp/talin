use serde::{Deserialize, Serialize};
use serde_with::skip_serializing_none;

use crate::utils::tagged_enum;
use crate::xai_responses::types::{
    ModelOutput, ModelResponseConfiguration, ModelTool, ModelToolChoice, ModelToolChoiceMode,
    ModelUsage, ReasoningConfiguration, ServiceTier, Truncation,
};

/// The response body for the [Create Response](https://docs.x.ai/docs/api-reference#create-new-response) endpoint.
#[skip_serializing_none]
#[cfg_attr(test, derive(utoipa::ToSchema))]
#[derive(Serialize, Deserialize, Debug, Clone)]
#[non_exhaustive]
pub struct ModelResponse {
    /// Whether to process the response asynchronously in the background.
    pub background: bool,

    /// The Unix timestamp (in seconds) at which the response was completed.
    pub completed_at: Option<i64>,

    /// The Unix timestamp (in seconds) for the response creation time.
    pub created_at: i64,

    /// An error object returned when the model fails to generate a response.
    #[cfg_attr(test, schema(value_type = Option<serde_json::Value>))]
    pub error: Option<ResponseError>,

    /// Not supported in the Responses API.
    /// Only maintained for compatibility reasons.
    pub frequency_penalty: f32,

    /// Unique ID of the response.
    pub id: String,

    /// Details about why the response is incomplete.
    pub incomplete_details: Option<IncompleteDetails>,

    /// A system (or developer) message inserted into the model's context.
    pub instructions: Option<String>,

    /// Max number of tokens that can be generated in a response.
    /// This includes both output and reasoning tokens.
    pub max_output_tokens: Option<u32>,

    /// The maximum number of tool calls allowed for this response.
    pub max_tool_calls: Option<u32>,

    /// Only included for compatibility.
    pub metadata: serde_json::Value,

    /// Model name used to generate the response.
    pub model: String,

    /// The object type of this resource. Always set to `"response"`.
    pub object: String,

    /// The response generated by the model.
    pub output: Vec<ModelOutput>,

    /// Whether to allow the model to run parallel tool calls.
    pub parallel_tool_calls: bool,

    /// Not supported in the Responses API.
    /// Only maintained for compatibility reasons.
    pub presence_penalty: f32,

    /// The ID of the previous response from the model.
    pub previous_response_id: Option<String>,

    /// The cache key used for the prompt for routing to the correct engine.
    pub prompt_cache_key: Option<String>,

    /// Reasoning configuration. Only for reasoning models.
    pub reasoning: Option<ReasoningConfiguration>,

    /// A stable identifier used to help detect users of your application that may be violating
    /// xAI's usage policies.
    pub safety_identifier: Option<String>,

    /// Processing tier for a request. Determines scheduling priority and billing.
    pub service_tier: ServiceTier,

    /// Status of the response.
    #[cfg_attr(test, schema(value_type = String))]
    pub status: ResponseStatus,

    /// Whether to store the input message(s) and model response for later retrieval.
    pub store: bool,

    /// What sampling temperature to use, between 0 and 2.
    #[cfg_attr(test, schema(minimum = 0, maximum = 2))]
    pub temperature: Option<f32>,

    /// Settings for customizing a text response from the model.
    pub text: ModelResponseConfiguration,

    /// Controls which (if any) tool is called by the model.
    pub tool_choice: ModelToolChoice,

    /// A list of tools the model may call in JSON-schema.
    #[cfg_attr(test, schema(max_items = 128))]
    pub tools: Vec<ModelTool>,

    /// An integer between 0 and 8 specifying the number of most likely tokens to return at each
    /// token position, each with an associated log probability.
    pub top_logprobs: u8,

    /// An alternative to sampling with [`temperature`](Self::temperature), called nucleus
    /// sampling.
    #[cfg_attr(test, schema(exclusive_minimum = 0, maximum = 1))]
    pub top_p: Option<f32>,

    /// The truncation strategy used for the model response.
    #[cfg_attr(test, schema(value_type = String))]
    pub truncation: Truncation,

    /// Token usage information.
    pub usage: Option<ModelUsage>,

    /// A unique identifier representing your end-user.
    pub user: Option<String>,
}

/// An error object returned when the model fails to generate a response.
#[skip_serializing_none]
#[cfg_attr(test, derive(utoipa::ToSchema))]
#[derive(Serialize, Deserialize, Debug, Clone, Default)]
#[non_exhaustive]
pub struct ResponseError {
    /// The error code.
    pub code: Option<String>,

    /// A human-readable description of the error.
    pub message: Option<String>,
}

tagged_enum! {
    /// Details about why a response is incomplete.
    #[derive(Serialize, Deserialize, Debug, Clone, PartialEq, Eq)]
    #[serde(tag = "reason", rename_all = "snake_case")]
    pub enum IncompleteDetails {
        /// The response hit the output token limit.
        MaxOutputTokens,
        /// The response hit the prompt token limit.
        MaxPromptTokens,
        /// The response hit the time limit.
        MaxTimeLimit,
        /// The response was filtered by the content filter.
        ContentFilter,
    }
}

/// Status of the response.
#[cfg_attr(test, derive(utoipa::ToSchema))]
#[derive(Serialize, Deserialize, Debug, Clone, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
#[non_exhaustive]
pub enum ResponseStatus {
    /// Completed.
    Completed,
    /// In progress.
    InProgress,
    /// Incomplete.
    Incomplete,

    /// A value not represented by this enum, kept as sent for forward compatibility.
    #[serde(untagged)]
    Unknown(String),
}

impl ModelResponse {
    /// Creates a [`ModelResponse`] with the given ID, model, creation time, status and output.
    ///
    /// Every other field is set to the API default.
    pub fn new(
        id: impl Into<String>,
        model: impl Into<String>,
        created_at: i64,
        status: ResponseStatus,
        output: Vec<ModelOutput>,
    ) -> Self {
        Self {
            background: false,
            completed_at: None,
            created_at,
            error: None,
            frequency_penalty: 0.0,
            id: id.into(),
            incomplete_details: None,
            instructions: None,
            max_output_tokens: None,
            max_tool_calls: None,
            metadata: serde_json::Value::Null,
            model: model.into(),
            object: "response".to_string(),
            output,
            parallel_tool_calls: true,
            presence_penalty: 0.0,
            previous_response_id: None,
            prompt_cache_key: None,
            reasoning: None,
            safety_identifier: None,
            service_tier: ServiceTier::Default,
            status,
            store: true,
            temperature: None,
            text: ModelResponseConfiguration::new(),
            tool_choice: ModelToolChoice::Mode(ModelToolChoiceMode::Auto),
            tools: Vec::new(),
            top_logprobs: 0,
            top_p: None,
            truncation: Truncation::Disabled,
            usage: None,
            user: None,
        }
    }

    /// Sets whether to process the response asynchronously in the background.
    pub fn with_background(mut self, background: bool) -> Self {
        self.background = background;
        self
    }

    /// Sets the Unix timestamp (in seconds) at which the response was completed.
    pub fn with_completed_at(mut self, completed_at: i64) -> Self {
        self.completed_at = Some(completed_at);
        self
    }

    /// Sets the error returned when the model fails to generate a response.
    pub fn with_error(mut self, error: ResponseError) -> Self {
        self.error = Some(error);
        self
    }

    /// Sets the `frequency_penalty` field (only maintained for compatibility reasons).
    pub fn with_frequency_penalty(mut self, frequency_penalty: f32) -> Self {
        self.frequency_penalty = frequency_penalty;
        self
    }

    /// Sets the details about why the response is incomplete.
    pub fn with_incomplete_details(mut self, incomplete_details: IncompleteDetails) -> Self {
        self.incomplete_details = Some(incomplete_details);
        self
    }

    /// Sets the system (or developer) message inserted into the model's context.
    pub fn with_instructions(mut self, instructions: impl Into<String>) -> Self {
        self.instructions = Some(instructions.into());
        self
    }

    /// Sets the maximum number of tokens that can be generated in a response.
    pub fn with_max_output_tokens(mut self, max_output_tokens: u32) -> Self {
        self.max_output_tokens = Some(max_output_tokens);
        self
    }

    /// Sets the maximum number of tool calls allowed for this response.
    pub fn with_max_tool_calls(mut self, max_tool_calls: u32) -> Self {
        self.max_tool_calls = Some(max_tool_calls);
        self
    }

    /// Sets the `metadata` field (only included for compatibility).
    pub fn with_metadata(mut self, metadata: serde_json::Value) -> Self {
        self.metadata = metadata;
        self
    }

    /// Sets the object type of this resource.
    pub fn with_object(mut self, object: impl Into<String>) -> Self {
        self.object = object.into();
        self
    }

    /// Sets whether to allow the model to run parallel tool calls.
    pub fn with_parallel_tool_calls(mut self, parallel_tool_calls: bool) -> Self {
        self.parallel_tool_calls = parallel_tool_calls;
        self
    }

    /// Sets the `presence_penalty` field (only maintained for compatibility reasons).
    pub fn with_presence_penalty(mut self, presence_penalty: f32) -> Self {
        self.presence_penalty = presence_penalty;
        self
    }

    /// Sets the ID of the previous response from the model.
    pub fn with_previous_response_id(mut self, previous_response_id: impl Into<String>) -> Self {
        self.previous_response_id = Some(previous_response_id.into());
        self
    }

    /// Sets the cache key used for the prompt for routing to the correct engine.
    pub fn with_prompt_cache_key(mut self, prompt_cache_key: impl Into<String>) -> Self {
        self.prompt_cache_key = Some(prompt_cache_key.into());
        self
    }

    /// Sets the reasoning configuration.
    pub fn with_reasoning(mut self, reasoning: ReasoningConfiguration) -> Self {
        self.reasoning = Some(reasoning);
        self
    }

    /// Sets the stable identifier used to help detect users violating xAI's usage policies.
    pub fn with_safety_identifier(mut self, safety_identifier: impl Into<String>) -> Self {
        self.safety_identifier = Some(safety_identifier.into());
        self
    }

    /// Sets the processing tier for the request.
    pub fn with_service_tier(mut self, service_tier: ServiceTier) -> Self {
        self.service_tier = service_tier;
        self
    }

    /// Sets whether to store the input message(s) and model response for later retrieval.
    pub fn with_store(mut self, store: bool) -> Self {
        self.store = store;
        self
    }

    /// Sets the sampling temperature used.
    pub fn with_temperature(mut self, temperature: f32) -> Self {
        self.temperature = Some(temperature);
        self
    }

    /// Sets the settings for customizing a text response from the model.
    pub fn with_text(mut self, text: ModelResponseConfiguration) -> Self {
        self.text = text;
        self
    }

    /// Sets which (if any) tool is called by the model.
    pub fn with_tool_choice(mut self, tool_choice: ModelToolChoice) -> Self {
        self.tool_choice = tool_choice;
        self
    }

    /// Sets the list of tools the model may call.
    pub fn with_tools(mut self, tools: Vec<ModelTool>) -> Self {
        self.tools = tools;
        self
    }

    /// Sets the number of most likely tokens returned at each token position.
    pub fn with_top_logprobs(mut self, top_logprobs: u8) -> Self {
        self.top_logprobs = top_logprobs;
        self
    }

    /// Sets the nucleus sampling parameter.
    pub fn with_top_p(mut self, top_p: f32) -> Self {
        self.top_p = Some(top_p);
        self
    }

    /// Sets the truncation strategy used for the model response.
    pub fn with_truncation(mut self, truncation: Truncation) -> Self {
        self.truncation = truncation;
        self
    }

    /// Sets the token usage information.
    pub fn with_usage(mut self, usage: ModelUsage) -> Self {
        self.usage = Some(usage);
        self
    }

    /// Sets the end-user identifier.
    pub fn with_user(mut self, user: impl Into<String>) -> Self {
        self.user = Some(user.into());
        self
    }
}

impl ResponseError {
    /// Creates an empty [`ResponseError`].
    pub fn new() -> Self {
        Self::default()
    }

    /// Sets the error code.
    pub fn with_code(mut self, code: impl Into<String>) -> Self {
        self.code = Some(code.into());
        self
    }

    /// Sets the human-readable description of the error.
    pub fn with_message(mut self, message: impl Into<String>) -> Self {
        self.message = Some(message.into());
        self
    }
}
