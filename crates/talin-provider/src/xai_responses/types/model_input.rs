use serde::{Deserialize, Serialize};
use serde_with::skip_serializing_none;

use crate::utils::tagged_enum;
use crate::xai_responses::types::{ModelOutput, Role};

/// Content of the input passed to a `/v1/response` request.
#[cfg_attr(test, derive(utoipa::ToSchema))]
#[derive(Serialize, Deserialize, Debug, Clone)]
#[serde(untagged)]
#[non_exhaustive]
pub enum ModelInput {
    /// Text input.
    Text(String),
    /// A list of input items to the model. Can be of different types.
    Parts(Vec<ModelInputPart>),
}

tagged_enum! {
    /// A single part of the model input.
    #[derive(Serialize, Deserialize, Debug, Clone)]
    #[serde(tag = "type", rename_all = "snake_case")]
    pub enum ModelInputPart {
        /// Message input to the model.
        @schema(title = "InputMessage")
        Message(InputMessage),
        /// The output of a function tool call.
        @schema(title = "FunctionToolCallOutput")
        FunctionCallOutput(FunctionToolCallOutput),
        /// The output of a shell tool call.
        @schema(title = "ShellCallOutput")
        ShellCallOutput(ShellCallOutput),
        /// A compaction item from a previous `/v1/responses/compact` call.
        @schema(title = "CompactionOutputItem")
        Compaction(CompactionOutputItem),
        /// The model output from a previous response.
        #[serde(untagged)]
        @schema(title = "ModelOutput")
        ModelOutput(ModelOutput),
    }
}

/// Message input to the model.
#[skip_serializing_none]
#[cfg_attr(test, derive(utoipa::ToSchema))]
#[derive(Serialize, Deserialize, Debug, Clone)]
#[non_exhaustive]
pub struct InputMessage {
    /// Text, image or audio input.
    pub content: ModelInputContent,

    /// The role of the message.
    #[cfg_attr(test, schema(value_type = String))]
    pub role: Role,

    /// A unique identifier representing your end-user.
    /// Only supported for `user` messages.
    pub name: Option<String>,
}

/// Content of the input passed to the model.
#[cfg_attr(test, derive(utoipa::ToSchema))]
#[derive(Serialize, Deserialize, Debug, Clone)]
#[serde(untagged)]
#[non_exhaustive]
pub enum ModelInputContent {
    /// Text input.
    Text(String),
    /// A list of input items to the model. Can include text and images.
    Parts(Vec<ModelInputContentItem>),
}

tagged_enum! {
    /// A single item in the model input content.
    #[derive(Serialize, Deserialize, Debug, Clone)]
    #[serde(tag = "type", rename_all = "snake_case")]
    pub enum ModelInputContentItem {
        /// Text input.
        InputText(InputTextItem),
        /// Text previously output by the model, passed back as input.
        OutputText(OutputTextItem),
        /// Image input.
        InputImage(InputImageItem),
        /// File input.
        InputFile(InputFileItem),
    }
}

/// Text previously output by the model, passed back as input.
#[cfg_attr(test, derive(utoipa::ToSchema))]
#[derive(Serialize, Deserialize, Debug, Clone)]
#[non_exhaustive]
pub struct OutputTextItem {
    /// The text the model output.
    pub text: String,
}

/// Text input item.
#[cfg_attr(test, derive(utoipa::ToSchema))]
#[derive(Serialize, Deserialize, Debug, Clone)]
#[non_exhaustive]
pub struct InputTextItem {
    /// Text input.
    pub text: String,
}

/// Image input item.
#[skip_serializing_none]
#[cfg_attr(test, derive(utoipa::ToSchema))]
#[derive(Serialize, Deserialize, Debug, Clone)]
#[non_exhaustive]
pub struct InputImageItem {
    /// A public URL of image prompt.
    pub image_url: String,

    /// Only included for compatibility.
    pub file_id: Option<String>,
}

/// File input item.
#[cfg_attr(test, derive(utoipa::ToSchema))]
#[derive(Serialize, Deserialize, Debug, Clone, Default)]
#[non_exhaustive]
pub struct InputFileItem {
    /// Inline file bytes (base64 encoded).
    ///
    /// When set, the file content is provided directly in the request and does NOT need to be
    /// uploaded to the Files API first.
    pub file_data: Option<String>,
    /// The file ID from the Files API.
    ///
    /// Set this to reference a previously-uploaded file.
    pub file_id: Option<String>,
    /// Public URL for a file attachment.
    ///
    /// When set, the file content is fetched from this URL
    pub file_url: Option<String>,
    /// The name of the file.
    pub filename: Option<String>,
    /// Optional MIME type for inline uploads (e.g. "application/pdf").
    pub mime_type: Option<String>,
}

/// The output of a function tool call.
#[cfg_attr(test, derive(utoipa::ToSchema))]
#[derive(Serialize, Deserialize, Debug, Clone)]
#[non_exhaustive]
pub struct FunctionToolCallOutput {
    /// The unique ID of the function tool call generated by the model.
    pub call_id: String,

    /// The output of the function tool call.
    /// Can be a plain string or a list of content items.
    pub output: ModelInputContent,
}

/// The output of a shell tool call, sent back after local execution.
#[skip_serializing_none]
#[cfg_attr(test, derive(utoipa::ToSchema))]
#[derive(Serialize, Deserialize, Debug, Clone)]
#[non_exhaustive]
pub struct ShellCallOutput {
    /// The unique ID of the shell tool call generated by the model.
    pub call_id: String,

    /// The maximum length of the shell command output.
    /// Generated by the model and should be passed back with the raw output.
    #[cfg_attr(test, schema(value_type = Option<i32>))]
    pub max_output_length: Option<u32>,

    /// An array of shell call output contents.
    pub output: Vec<ShellCallOutputResult>,
}

/// The content of a shell tool call output that was emitted.
#[cfg_attr(test, derive(utoipa::ToSchema))]
#[derive(Serialize, Deserialize, Debug, Clone)]
#[non_exhaustive]
pub struct ShellCallOutputResult {
    /// The outcome of the command execution.
    pub outcome: ShellCallOutcome,

    /// The standard error output that was captured.
    #[cfg_attr(test, schema(nullable = false))]
    pub stderr: Option<String>,

    /// The standard output that was captured.
    #[cfg_attr(test, schema(nullable = false))]
    pub stdout: Option<String>,
}

tagged_enum! {
    /// The outcome of a shell command execution.
    #[derive(Serialize, Deserialize, Debug, Clone)]
    #[serde(tag = "type", rename_all = "snake_case")]
    pub enum ShellCallOutcome {
        /// The command exited normally.
        Exit {
        /// The exit code of the command.
        exit_code: i32,
        },
        /// The command timed out.
        Timeout,
    }
}

/// A compaction item from a previous `/v1/responses/compact` call.
///
/// Accepted as input in `/v1/responses` calls. The
/// [`encrypted_content`](Self::encrypted_content) is opaque: do not parse or depend on its
/// internal structure.
#[skip_serializing_none]
#[cfg_attr(test, derive(utoipa::ToSchema))]
#[derive(Serialize, Deserialize, Debug, Clone)]
#[non_exhaustive]
pub struct CompactionOutputItem {
    /// The encrypted content of the compacted conversation.
    pub encrypted_content: String,

    /// The unique ID of the compaction item (e.g. `cmp_<uuid>`).
    pub id: Option<String>,
}

impl InputMessage {
    /// Creates an [`InputMessage`] with the given content and role.
    pub fn new(content: ModelInputContent, role: Role) -> Self {
        Self {
            content,
            role,
            name: None,
        }
    }

    /// Sets the end-user identifier (only supported for `user` messages).
    pub fn with_name(mut self, name: impl Into<String>) -> Self {
        self.name = Some(name.into());
        self
    }
}

impl OutputTextItem {
    /// Creates an [`OutputTextItem`] with the given text.
    pub fn new(text: impl Into<String>) -> Self {
        Self { text: text.into() }
    }
}

impl InputTextItem {
    /// Creates an [`InputTextItem`] with the given text.
    pub fn new(text: impl Into<String>) -> Self {
        Self { text: text.into() }
    }
}

impl InputImageItem {
    /// Creates an [`InputImageItem`] with the given image URL.
    pub fn new(image_url: impl Into<String>) -> Self {
        Self {
            image_url: image_url.into(),
            file_id: None,
        }
    }

    /// Sets the `file_id` field (only included for compatibility).
    pub fn with_file_id(mut self, file_id: impl Into<String>) -> Self {
        self.file_id = Some(file_id.into());
        self
    }
}

impl InputFileItem {
    /// Creates a new [`InputFileItem`].
    ///
    /// Must set at least one of `file_data`, `file_id`, or `file_url` to be valid.
    pub fn new() -> Self {
        Self::default()
    }

    /// Sets the inline file bytes (base64 encoded) and their MIME type.
    ///
    /// A file provided this way does not need to be uploaded to the Files API first.
    pub fn with_file_data(
        mut self,
        file_data: impl Into<String>,
        mime_type: impl Into<String>,
    ) -> Self {
        self.file_data = Some(file_data.into());
        self.mime_type = Some(mime_type.into());
        self
    }

    /// Sets the file ID of a previously-uploaded file from the Files API.
    pub fn with_file_id(mut self, file_id: impl Into<String>) -> Self {
        self.file_id = Some(file_id.into());
        self
    }

    /// Sets the public URL the file content is fetched from.
    pub fn with_file_url(mut self, file_url: impl Into<String>) -> Self {
        self.file_url = Some(file_url.into());
        self
    }

    /// Sets the name of the file.
    pub fn with_filename(mut self, filename: impl Into<String>) -> Self {
        self.filename = Some(filename.into());
        self
    }
}

impl FunctionToolCallOutput {
    /// Creates a [`FunctionToolCallOutput`] for the given call ID and textual output.
    pub fn new(call_id: impl Into<String>, output: impl Into<String>) -> Self {
        Self::with_content(call_id, ModelInputContent::Text(output.into()))
    }

    /// Creates a [`FunctionToolCallOutput`] for the given call ID and output content.
    pub fn with_content(call_id: impl Into<String>, output: ModelInputContent) -> Self {
        Self {
            call_id: call_id.into(),
            output,
        }
    }
}

impl ShellCallOutput {
    /// Creates a [`ShellCallOutput`] for the given call ID and results.
    pub fn new(call_id: impl Into<String>, output: Vec<ShellCallOutputResult>) -> Self {
        Self {
            call_id: call_id.into(),
            max_output_length: None,
            output,
        }
    }

    /// Sets the maximum length of the shell command output.
    pub fn with_max_output_length(mut self, max_output_length: u32) -> Self {
        self.max_output_length = Some(max_output_length);
        self
    }
}

impl ShellCallOutputResult {
    /// Creates a [`ShellCallOutputResult`] with the given outcome.
    pub fn new(outcome: ShellCallOutcome) -> Self {
        Self {
            outcome,
            stderr: None,
            stdout: None,
        }
    }

    /// Sets the captured standard error output.
    pub fn with_stderr(mut self, stderr: impl Into<String>) -> Self {
        self.stderr = Some(stderr.into());
        self
    }

    /// Sets the captured standard output.
    pub fn with_stdout(mut self, stdout: impl Into<String>) -> Self {
        self.stdout = Some(stdout.into());
        self
    }
}

impl CompactionOutputItem {
    /// Creates a [`CompactionOutputItem`] carrying the given encrypted content.
    pub fn new(encrypted_content: impl Into<String>) -> Self {
        Self {
            encrypted_content: encrypted_content.into(),
            id: None,
        }
    }

    /// Sets the unique ID of the compaction item.
    pub fn with_id(mut self, id: impl Into<String>) -> Self {
        self.id = Some(id.into());
        self
    }
}

impl Default for ModelInput {
    fn default() -> Self {
        Self::Parts(Vec::new())
    }
}
