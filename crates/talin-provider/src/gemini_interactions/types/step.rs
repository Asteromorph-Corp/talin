tagged_enum! {
    /// A single step in an interaction.
    ///
    /// Steps are discriminated by their `type` field. An interaction is an ordered sequence
    /// of steps: user input, model output, thoughts, tool calls, and tool results.
    #[derive(Serialize, Deserialize, Debug, Clone)]
    #[serde(tag = "type", rename_all = "snake_case")]
    pub enum Step {
        /// Input provided by the user.
        UserInput(UserInputStep),
        /// Output generated by the model.
        ModelOutput(ModelOutputStep),
        /// A thought produced by a thinking model.
        Thought(ThoughtStep),
        /// A function tool call.
        FunctionCall(FunctionCallStep),
        /// A code execution tool call.
        CodeExecutionCall(CodeExecutionCallStep),
        /// A URL context tool call.
        UrlContextCall(UrlContextCallStep),
        /// A Google Search tool call.
        GoogleSearchCall(GoogleSearchCallStep),
        /// A file search tool call.
        FileSearchCall(FileSearchCallStep),
        /// A Google Maps tool call.
        GoogleMapsCall(GoogleMapsCallStep),
        /// An MCP server tool call.
        McpServerToolCall(McpServerToolCallStep),
        /// The result of a function tool call.
        FunctionResult(FunctionResultStep),
        /// The result of a code execution tool call.
        CodeExecutionResult(CodeExecutionResultStep),
        /// The result of a URL context tool call.
        UrlContextResult(UrlContextResultStep),
        /// The result of a Google Search tool call.
        GoogleSearchResult(GoogleSearchResultStep),
        /// The result of a file search tool call.
        FileSearchResult(FileSearchResultStep),
        /// The result of a Google Maps tool call.
        GoogleMapsResult(GoogleMapsResultStep),
        /// The result of a MCP server tool call.
        McpServerToolResult(McpServerToolResultStep),
        /// A server-initiated media processing step.
        ProcessingCall(ProcessingCallStep),
        /// The result of a server-initiated media processing step.
        ProcessingResult(ProcessingResultStep),
    }
}

