tagged_enum! {
    /// A content block within a system prompt. Can only be a text block.
    #[derive(Serialize, Deserialize, Debug, Clone)]
    #[serde(tag = "type", rename_all = "snake_case")]
    pub enum SystemBlockParam {
        /// A text block.
        Text(TextBlockParam),
    }
}

tagged_enum! {
    /// A content block within a request message.
    #[derive(Serialize, Debug, Clone)]
    #[serde(tag = "type", rename_all = "snake_case")]
    pub enum ContentBlockParam {
        /// A text block.
        Text(TextBlockParam),
        /// An image block.
        Image(ImageBlockParam),
        /// A document block.
        Document(DocumentBlockParam),
        /// A search result block. Used to provide results from custom search tools.
        SearchResult(SearchResultBlockParam),
        /// A thinking block. Returned when Claude goes through an internal reasoning process.
        Thinking(ThinkingBlockParam),
        /// A redacted thinking block. Returned when the internal reasoning generated by Claude is
        /// flagged by Anthropic's safety systems.
        RedactedThinking(RedactedThinkingBlockParam),
        /// A tool use block. Returned when Claude decides to invoke a user-defined tool.
        ToolUse(ToolUseBlockParam),
        /// A tool result block. Used to provide the results of a user-defined tool invocation.
        ToolResult(ToolResultBlockParam),
        /// A server tool use block. Returned when Claude invokes an internal tool.
        ServerToolUse(ServerToolUseBlockParam),
        /// A web search tool result block. When Claude invokes its internal web search tool, this is
        /// returned along with a server tool use block.
        WebSearchToolResult(WebSearchToolResultBlockParam),
        /// A web fetch tool result block. When Claude invokes its internal web fetch tool, this is
        /// returned along with a server tool use block.
        WebFetchToolResult(WebFetchToolResultBlockParam),
        /// A code execution tool result block. When Claude invokes its internal code execution tool,
        /// this is returned along with a server tool use block.
        CodeExecutionToolResult(CodeExecutionToolResultBlockParam),
        /// A bash code execution tool result block. When Claude invokes its internal bash code
        /// execution tool, this is returned along with a server tool use block.
        BashCodeExecutionToolResult(BashCodeExecutionToolResultBlockParam),
        /// A text editor code execution tool result block. When Claude invokes its internal text
        /// editor code execution tool, this is returned along with a server tool use block.
        TextEditorCodeExecutionToolResult(TextEditorCodeExecutionToolResultBlockParam),
        /// A tool search tool result block. When Claude invokes its internal tool search tool, this is
        /// returned along with a server tool use block.
        ToolSearchToolResult(ToolSearchToolResultBlockParam),
        /// A container upload block. Uploads a file to the container.
        ContainerUpload(ContainerUploadBlockParam),
        /// A previous compaction summary sent back to preserve context.
        Compaction(CompactionBlockParam),
        /// An MCP tool use block. Returned when Claude invokes a tool provided by one of the MCP
        /// servers.
        #[cfg(feature = "mcp-client-2025-11-20")]
        McpToolUse(McpToolUseBlock),
        /// An MCP tool result block. When Claude invokes a tool provided by one of the MCP servers,
        /// this is returned along with an MCP tool use block.
        #[cfg(feature = "mcp-client-2025-11-20")]
        McpToolResult(McpToolResultBlockParam),
    }
}

tagged_enum! {
    /// A content block within a response message.
    #[derive(Deserialize, Debug, Clone)]
    #[serde(tag = "type", rename_all = "snake_case")]
    pub enum ContentBlock {
        /// A text block.
        Text(TextBlock),
        /// A thinking block. Returned when Claude goes through an internal reasoning process.
        Thinking(ThinkingBlock),
        /// A redacted thinking block. Returned when the internal reasoning generated by Claude is
        /// flagged by Anthropic's safety systems.
        RedactedThinking(RedactedThinkingBlock),
        /// A tool use block. Returned when Claude decides to invoke a user-defined tool.
        ToolUse(ToolUseBlock),
        /// A server tool use block. Returned when Claude invokes an internal tool.
        ServerToolUse(ServerToolUseBlock),
        /// A web search tool result block. When Claude invokes its internal web search tool, this is
        /// returned along with a server tool use block.
        WebSearchToolResult(WebSearchToolResultBlock),
        /// A web fetch tool result block. When Claude invokes its internal web fetch tool, this is
        /// returned along with a server tool use block.
        WebFetchToolResult(WebFetchToolResultBlock),
        /// A code execution tool result block. When Claude invokes its internal code execution tool,
        /// this is returned along with a server tool use block.
        CodeExecutionToolResult(CodeExecutionToolResultBlock),
        /// A bash code execution tool result block. When Claude invokes its internal bash code
        /// execution tool, this is returned along with a server tool use block.
        BashCodeExecutionToolResult(BashCodeExecutionToolResultBlock),
        /// A text editor code execution tool result block. When Claude invokes its internal text
        /// editor code execution tool, this is returned along with a server tool use block.
        TextEditorCodeExecutionToolResult(TextEditorCodeExecutionToolResultBlock),
        /// A tool search tool result block. When Claude invokes its internal tool search tool, this is
        /// returned along with a server tool use block.
        ToolSearchToolResult(ToolSearchToolResultBlock),
        /// A container upload block. Returned when Claude uploads a file to a container.
        ContainerUpload(ContainerUploadBlock),
        /// A summary of older conversation context.
        Compaction(CompactionBlock),
        /// An MCP tool use block. Returned when Claude invokes a tool provided by one of the MCP
        /// servers.
        #[cfg(feature = "mcp-client-2025-11-20")]
        McpToolUse(McpToolUseBlock),
        /// An MCP tool result block. When Claude invokes a tool provided by one of the MCP servers,
        /// this is returned along with an MCP tool use block.
        #[cfg(feature = "mcp-client-2025-11-20")]
        McpToolResult(McpToolResultBlockParam),
    }
}

impl From<ContentBlock> for ContentBlockParam {
    fn from(value: ContentBlock) -> Self {
        match value {
            ContentBlock::Text(text) => ContentBlockParam::Text(text.into()),
            ContentBlock::Thinking(thinking) => ContentBlockParam::Thinking(thinking.into()),
            ContentBlock::RedactedThinking(redacted_thinking) => {
                ContentBlockParam::RedactedThinking(redacted_thinking.into())
            }
            ContentBlock::ToolUse(tool_use) => ContentBlockParam::ToolUse(tool_use.into()),
            ContentBlock::ServerToolUse(tool_use) => {
                ContentBlockParam::ServerToolUse(tool_use.into())
            }
            ContentBlock::WebSearchToolResult(result) => {
                ContentBlockParam::WebSearchToolResult(result.into())
            }
            ContentBlock::WebFetchToolResult(result) => {
                ContentBlockParam::WebFetchToolResult(result.into())
            }
            ContentBlock::CodeExecutionToolResult(result) => {
                ContentBlockParam::CodeExecutionToolResult(result.into())
            }
            ContentBlock::BashCodeExecutionToolResult(result) => {
                ContentBlockParam::BashCodeExecutionToolResult(result.into())
            }
            ContentBlock::TextEditorCodeExecutionToolResult(result) => {
                ContentBlockParam::TextEditorCodeExecutionToolResult(result.into())
            }
            ContentBlock::ToolSearchToolResult(result) => {
                ContentBlockParam::ToolSearchToolResult(result.into())
            }
            #[cfg(feature = "mcp-client-2025-11-20")]
            ContentBlock::McpToolUse(tool_use) => ContentBlockParam::McpToolUse(tool_use),
            #[cfg(feature = "mcp-client-2025-11-20")]
            ContentBlock::McpToolResult(result) => ContentBlockParam::McpToolResult(result),
            ContentBlock::ContainerUpload(upload) => {
                ContentBlockParam::ContainerUpload(upload.into())
            }
            ContentBlock::Compaction(block) => ContentBlockParam::Compaction(block.into()),
            ContentBlock::Unknown(value) => ContentBlockParam::Unknown(value),
        }
    }
}
