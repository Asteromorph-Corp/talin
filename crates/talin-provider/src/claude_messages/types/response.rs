use serde::Deserialize;

use crate::claude_messages::types::{
    Container, ContentBlock, Diagnostics, Model, RefusalStopDetails, StopReason, Usage,
};
use crate::utils::fixed_value;

/// A successful response from the Messages endpoint.
#[cfg_attr(test, derive(utoipa::ToSchema))]
#[derive(Deserialize, Debug, Clone)]
#[non_exhaustive]
pub struct MessagesResponse {
    /// The type of the object.
    ///
    /// This will always be `"message"`.
    ///
    /// See [`type`](https://docs.claude.com/en/api/messages#response-type)
    #[serde(rename = "type")]
    pub type_: MessageType,

    /// Unique object identifier.
    ///
    /// See [`id`](https://docs.claude.com/en/api/messages#response-id)
    pub id: String,

    /// Conversational role of the generated message.
    ///
    /// This will always be `"assistant"`.
    ///
    /// See [`role`](https://docs.claude.com/en/api/messages#response-role)
    pub role: ResponseRole,

    /// Content generated by the model.
    ///
    /// See [`content`](https://docs.claude.com/en/api/messages#response-content)
    pub content: Vec<ContentBlock>,

    /// The model that handled the request.
    ///
    /// See [`model`](https://docs.claude.com/en/api/messages#response-model)
    pub model: Model,

    // Should be serialized as `null` if `None`.
    /// The reason that Claude stopped.
    ///
    /// See [`stop_reason`](https://docs.claude.com/en/api/messages#response-stop-reason)
    #[cfg_attr(test, schema(required = true))]
    pub stop_reason: Option<StopReason>,

    // Should be serialized as `null` if `None`.
    /// Which custom stop sequence was generated, if any.
    ///
    /// See [`stop_sequence`](https://docs.claude.com/en/api/messages#response-stop-sequence)
    #[cfg_attr(test, schema(required = true))]
    pub stop_sequence: Option<String>,

    // Should be serialized as `null` if `None`.
    /// Structured information about why the model stopped.
    #[cfg_attr(test, schema(required = true))]
    pub stop_details: Option<RefusalStopDetails>,

    /// Billing and rate-limit usage.
    ///
    /// See [`usage`](https://docs.claude.com/en/api/messages#response-usage)
    pub usage: Usage,

    /// Information about the container used in this request.
    ///
    /// See [`container`](https://docs.claude.com/en/api/messages#response-container)
    #[cfg_attr(test, schema(required = true))]
    pub container: Option<Container>,

    // Should be serialized as `null` if `None`.
    /// Request-level diagnostics.
    ///
    /// `None` when the request did not supply `diagnostics`, or when it did and no prompt-cache
    /// divergence was detected.
    #[cfg_attr(test, schema(required = true))]
    pub diagnostics: Option<Diagnostics>,
}

/// Conversational role of the generated message, as returned in a response.
///
/// This will always be `"assistant"`.
#[cfg_attr(test, derive(utoipa::ToSchema))]
#[derive(Deserialize, Debug, Clone, Copy)]
#[serde(rename_all = "lowercase")]
#[non_exhaustive]
pub enum ResponseRole {
    /// `"assistant"`
    Assistant,
}

impl MessagesResponse {
    /// Creates a new [`MessagesResponse`] from the given id, content, model, and usage.
    pub fn new(
        id: impl Into<String>,
        content: Vec<ContentBlock>,
        model: impl Into<Model>,
        usage: Usage,
    ) -> Self {
        Self {
            type_: MessageType::Message,
            id: id.into(),
            role: ResponseRole::Assistant,
            content,
            model: model.into(),
            stop_reason: None,
            stop_sequence: None,
            stop_details: None,
            usage,
            container: None,
            diagnostics: None,
        }
    }

    /// Sets the [`stop_reason`](Self::stop_reason) for the response.
    pub fn with_stop_reason(mut self, stop_reason: StopReason) -> Self {
        self.stop_reason = Some(stop_reason);
        self
    }

    /// Sets the [`stop_sequence`](Self::stop_sequence) that was generated.
    pub fn with_stop_sequence(mut self, stop_sequence: impl Into<String>) -> Self {
        self.stop_sequence = Some(stop_sequence.into());
        self
    }

    /// Sets the [`stop_details`](Self::stop_details) for the response.
    pub fn with_stop_details(mut self, stop_details: RefusalStopDetails) -> Self {
        self.stop_details = Some(stop_details);
        self
    }

    /// Sets the [`container`](Self::container) used in the request.
    pub fn with_container(mut self, container: Container) -> Self {
        self.container = Some(container);
        self
    }

    /// Sets the [`diagnostics`](Self::diagnostics) of the response.
    pub fn with_diagnostics(mut self, diagnostics: Diagnostics) -> Self {
        self.diagnostics = Some(diagnostics);
        self
    }
}

fixed_value!(MessageType::Message);

impl From<MessagesResponse> for super::MessageParam {
    fn from(response: MessagesResponse) -> Self {
        response.content.into()
    }
}

impl From<Vec<ContentBlock>> for super::MessageParam {
    fn from(content: Vec<ContentBlock>) -> Self {
        Self::assistant(super::TextOrItems::Items(
            content.into_iter().map(Into::into).collect(),
        ))
    }
}
