fn call_options() -> ::talin::llm::LlmOptions {
    ::talin::llm::LlmOptions::default()
        .with_stream(true)
        .with_tool_choice(::talin::schemas::ToolChoice::Auto)
        .with_parallel_tool_calls(false)
        .with_n(2u8)
        .with_reasoning_effort(::talin::schemas::ReasoningEffort::High)
        .with_temperature(0.7f32)
        .with_top_p(0.9f32)
        .with_top_k(40u32)
        .with_frequency_penalty(0.1f32)
        .with_presence_penalty(0.2f32)
        .with_repetition_penalty(1.1f32)
        .with_max_tokens(1024u32)
        .with_max_completion_tokens(512u32)
        .with_stop_words(vec![String::from("STOP"), String::from("END")])
        .with_extra_params(std::collections::HashMap::from_iter([
            (
                String::from("a_bool"),
                ::talin::__private::serde_json::Value::Bool(true),
            ),
            (
                String::from("a_datetime"),
                ::talin::__private::serde_json::Value::String(String::from(
                    "1979-05-27T07:32:00Z",
                )),
            ),
            (
                String::from("a_float"),
                ::talin::__private::serde_json::Value::Number(
                    ::talin::__private::serde_json::Number::from_f64(3.5f64)
                        .expect("toml float is finite"),
                ),
            ),
            (
                String::from("a_string"),
                ::talin::__private::serde_json::Value::String(String::from("hello")),
            ),
            (
                String::from("a_table"),
                ::talin::__private::serde_json::Value::Object(
                    ::talin::__private::serde_json::Map::from_iter([(
                        String::from("nested"),
                        ::talin::__private::serde_json::Value::String(String::from(
                            "value",
                        )),
                    )]),
                ),
            ),
            (
                String::from("an_array"),
                ::talin::__private::serde_json::Value::Array(vec![
                    ::talin::__private::serde_json::Value::Number(
                        ::talin::__private::serde_json::Number::from(1i64),
                    ),
                    ::talin::__private::serde_json::Value::Number(
                        ::talin::__private::serde_json::Number::from(2i64),
                    ),
                    ::talin::__private::serde_json::Value::Number(
                        ::talin::__private::serde_json::Number::from(3i64),
                    ),
                ]),
            ),
            (
                String::from("an_int"),
                ::talin::__private::serde_json::Value::Number(
                    ::talin::__private::serde_json::Number::from(42i64),
                ),
            ),
        ]))
}
